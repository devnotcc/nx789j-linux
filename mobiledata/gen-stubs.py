#!/usr/bin/env python3
# Generates NxCb*.java: concrete subclasses of the radio AIDL callback Stubs
# (IRadio*Response / IRadio*Indication) in which every method forwards to Ev.on(name, args).
# Input: `javap -public` output of the interface classes (argv[1] = javap text file).
import re, sys

src = open(sys.argv[1]).read()
out = {}
cur = None
for line in src.splitlines():
    m = re.match(r'public interface (android\.hardware\.radio\.[\w.]+\.(IRadio\w+))\b', line)
    if m:
        cur = (m.group(1), m.group(2)); out[cur] = []; continue
    if cur is None:
        continue
    m = re.match(r'\s+public abstract (\S+) (\w+)\((.*)\) throws android\.os\.RemoteException;', line)
    if m and m.group(2) not in ('getInterfaceVersion', 'getInterfaceHash', 'asBinder'):
        params = [p.strip() for p in m.group(3).split(',') if p.strip()]
        out[cur].append((m.group(1), m.group(2), params))

for (fq, short), methods in out.items():
    cls = 'NxCb' + short[len('IRadio'):]
    body = ['// generated by gen-stubs.py - do not edit',
            'public class %s extends %s.Stub {' % (cls, fq),
            '    @Override public String getInterfaceHash() { return %s.HASH; }' % fq,
            '    @Override public int getInterfaceVersion() { return %s.VERSION; }' % fq]
    for ret, name, params in methods:
        if ret != 'void':
            sys.exit('unexpected return type %s %s' % (ret, name))
        args = ', '.join('%s a%d' % (t, i) for i, t in enumerate(params))
        vals = ', '.join('a%d' % i for i in range(len(params)))
        body.append('    @Override public void %s(%s) { Ev.on("%s", new Object[] {%s}); }' % (name, args, name, vals))
    body.append('}')
    open(cls + '.java', 'w').write('\n'.join(body) + '\n')
    print(cls, len(methods))
